const k = (p1: number, p2: number, p3: number) =>
  `${p1.toString().padStart(2, "0")}-${p2.toString().padStart(2, "0")}-${p3
    .toString()
    .padStart(2, "0")}`;

export function describe(p1: number, p2: number, p3: number): string | null {
  // Preset 2..5 share descriptions with preset 1.
  if (p1 === 9 && p2 >= 2 && p2 <= 5) {
    return D[k(9, 1, p3)] ?? null;
  }
  return D[k(p1, p2, p3)] ?? null;
}
